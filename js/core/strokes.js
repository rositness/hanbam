// Используются для прописей: образец, номера черт и анимация порядка написания.

const circle = (cx, cy, r, n = 28) => {
  // Круг ㅇ пишется одним движением против часовой стрелки, начиная сверху.
  const pts = [];
  for (let i = 0; i <= n; i++) {
    const a = -Math.PI / 2 - (i / n) * Math.PI * 2;
    pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  return pts;
};
// Перенос штрихов в полосу по горизонтали (для двойных согласных и сложных гласных).
const fitX = (strokes, x0, x1) => strokes.map((s) => s.map(([x, y]) => [x0 + (x / 100) * (x1 - x0), y]));

